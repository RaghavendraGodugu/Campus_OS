/**
 * Announcement images.
 *
 * ## Why this is a separate call from creating the announcement
 *
 * `POST /announcements` takes JSON and is validated strictly. Turning it into a
 * multipart endpoint would mean every field arriving as a string — `pinned` and
 * `priority` would need coercion and `audience` would need parsing — which
 * weakens a well-tested endpoint to serve one optional field.
 *
 * So the announcement is created first, then the image is attached to it. Two
 * requests, and the existing create endpoint is untouched.
 *
 * ## Images only
 *
 * An announcement image is shown inline in a list, so a PDF has nothing to be.
 * Unlike document storage, this allowlist contains no PDFs — accepting one
 * would mean uploading something that cannot be rendered where it is used.
 *
 * The file goes through the same adapter as every other upload, which means
 * Cloudinary's `image` pipeline: transcoded and optimised on delivery. The
 * declared MIME type is never trusted; the type is sniffed from the bytes.
 */

const Announcement = require("../models/Announcement");
const { getStorage, sniffMimeType } = require("../config/storage");
const { ApiError } = require("../utils/ApiError");
const { logger } = require("../config/logger");

/** The only types an announcement image may be. */
const ALLOWED_IMAGE_TYPES = Object.freeze({
  "image/jpeg": "jpg",
  "image/png": "png",
});

/** Images are for inline display, so the ceiling is lower than for documents. */
const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

/**
 * Keep the client's filename for display only, never for storage.
 *
 * This value is rendered, so it strips anything that could become markup, and
 * path separators, so a name like `../../../etc/passwd.png` cannot survive as a
 * traversal-looking string in an audit log or a download filename.
 */
function safeDisplayName(name) {
  const cleaned = String(name ?? "image")
    .replace(/[\r\n\t]/g, " ")
    .replace(/[<>&"'`]/g, "")
    .replace(/\.[^.]*$/, "")
    // Collapse separators before trimming, or "../../x" becomes ".. x".
    .replace(/[\\/]+/g, " ")
    .replace(/\.{2,}/g, "")
    .trim()
    .replace(/\s+/g, " ")
    .slice(0, 80);

  return cleaned || "image";
}

/**
 * Load an announcement by its reference, the same identifier every other
 * announcement route accepts.
 *
 * The reference is what the UI has: the compose page navigates to
 * `/announcements/AN-2026-000002`. Accepting only an ObjectId here made every
 * image upload 404 against a real, valid announcement.
 */
async function loadAnnouncement(id) {
  const reference = String(id ?? "")
    .trim()
    .toUpperCase();
  if (!reference) {
    throw ApiError.notFound("Announcement not found");
  }

  const announcement = await Announcement.findOne({ reference });
  if (!announcement) {
    throw ApiError.notFound("Announcement not found");
  }
  return announcement;
}

/**
 * Attach an image to an announcement, replacing any previous one.
 *
 * @param {{announcementId: string, file: object, user: object, req?: object}} args
 * @returns {Promise<object>} the updated attachment record
 */
async function attachImage({ announcementId, file, user, req }) {
  const announcement = await loadAnnouncement(announcementId);

  if (!file?.buffer || file.buffer.length === 0) {
    throw ApiError.badRequest("The uploaded image is empty.");
  }

  if (file.buffer.length > MAX_IMAGE_BYTES) {
    throw ApiError.badRequest("Image is too large. The maximum is 5 MB.");
  }

  // The client's Content-Type is a claim. Only the bytes are evidence.
  const verified = sniffMimeType(file.buffer);

  if (!verified || !ALLOWED_IMAGE_TYPES[verified]) {
    logger.warn(
      {
        userId: user._id,
        declared: file.mimetype,
        originalName: file.originalname,
        bytes: file.buffer.length,
      },
      "Rejected an announcement image whose content is not a JPEG or PNG"
    );
    throw ApiError.badRequest("Upload a JPEG or PNG image.");
  }

  const storage = getStorage();
  const previousKey = announcement.attachment?.storageKey ?? null;

  const stored = await storage.save(file.buffer, {
    folder: "announcements",
    // Generated by the adapter, never from the client's filename.
    filename: `announcement-${announcement._id}.${ALLOWED_IMAGE_TYPES[verified]}`,
    mimeType: verified,
  });

  announcement.attachment = {
    storageKey: stored.key,
    originalName: safeDisplayName(file.originalname),
    mimeType: verified,
    bytes: stored.bytes ?? file.buffer.length,
    adapter: stored.adapter,
  };
  announcement.updatedBy = user._id;
  await announcement.save();

  // Only after the new image is committed, so a failure here cannot leave the
  // announcement pointing at bytes that no longer exist. A failure to clean up
  // leaks one orphaned object, which is recoverable; the reverse would publish
  // a broken image link.
  if (previousKey && previousKey !== stored.key) {
    try {
      await storage.delete(previousKey, { mimeType: announcement.attachment.mimeType });
    } catch (error) {
      logger.warn(
        { err: error, key: previousKey },
        "Replaced announcement image but could not delete the previous one"
      );
    }
  }

  logger.info(
    { announcementId: announcement._id, userId: user._id, reqId: req?.id },
    "Announcement image attached"
  );

  return announcement.attachment;
}

/** Remove an announcement's image, if it has one. */
async function removeImage({ announcementId, user }) {
  const announcement = await loadAnnouncement(announcementId);
  const key = announcement.attachment?.storageKey;

  announcement.attachment = {
    storageKey: null,
    originalName: null,
    mimeType: null,
    bytes: null,
    adapter: null,
  };
  announcement.updatedBy = user._id;
  await announcement.save();

  if (!key) return false;

  try {
    await getStorage().delete(key);
    return true;
  } catch (error) {
    logger.warn({ err: error, key }, "Announcement image removed but file delete failed");
    return false;
  }
}

module.exports = {
  attachImage,
  removeImage,
  loadAnnouncement,
  safeDisplayName,
  ALLOWED_IMAGE_TYPES,
  MAX_IMAGE_BYTES,
};
